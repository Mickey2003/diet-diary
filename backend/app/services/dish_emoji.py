_WS_RE = re.compile(r"\s+")


def emoji_for(dish_name: str, category: str = "") -> str:
    """返回菜名对应的 emoji（永不返回空）。"""
    name = _WS_RE.sub("", dish_name or "").strip()
    if not name:
        return CATEGORY_EMOJI.get(category, FALLBACK)

    # 1) 精确
    if name in _EXACT:
        return _EXACT[name]
    # 去掉常见修饰词后再试精确（如「清蒸鲈鱼（去皮）」）
    core = re.sub(r"[（(].*?[)）]", "", name)
    if core in _EXACT:
        return _EXACT[core]

    # 2) 关键词（长词优先）
    for kw, emo in _KEYWORDS_SORTED:
        if kw in name:
            return emo

    # 3) 类别
    return CATEGORY_EMOJI.get(category, FALLBACK)


def emoji_image_url(emoji: str, style: str = "twemoji") -> str:
    """把 emoji 转成可缓存的图片 URL。

    - twemoji：用 jsDelivr 托管的 Twemoji SVG（跨端渲染统一）
    - 其余/转换失败：空串，由前端直接用文本 emoji 渲染
    """
    if not emoji:
        return ""
    if style != "twemoji":
        return ""
    try:
        codepoints = [f"{ord(ch):x}" for ch in emoji if ch not in ("\ufe0f", "\u200d")]
        if not codepoints:
            return ""
        name = "-".join(codepoints)
        return f"https://cdn.jsdelivr.net/gh/twitter/twemoji@14.0.2/assets/svg/{name}.svg"
    except Exception:  # noqa: BLE001
        return ""


def build_emoji_entry(dish_name: str, category: str = "") -> Dict[str, str]:
    """给餐单菜品用的 emoji 展示描述。"""
    emo = emoji_for(dish_name, category)
    return {
        "image_emoji": emo,
        "image_emoji_url": emoji_image_url(emo),
        "image_bg": DEFAULT_BACKGROUND,
    }
