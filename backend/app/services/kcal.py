_KEYS_BY_LEN = sorted(TABLE.keys(), key=len, reverse=True)


def estimate_kcal(name: str, category: str = "其他", portion: str = "中") -> Tuple[int, str]:
    """返回 (估算千卡, 来源)。来源为 table（命中菜品表）或 category（仅按分类兜底）。"""
    factor = PORTION_FACTOR.get(portion or "中", 1.0)
    n = (name or "").strip()
    for key in _KEYS_BY_LEN:
        if key and key in n:
            return int(round(TABLE[key] * factor)), "table"
    return int(round(CATEGORY_DEFAULT.get(category, 150) * factor)), "category"


def kcal_from_nutriments(energy_kcal_100g: Optional[float], quantity_text: Optional[str] = None) -> Optional[int]:
    """条形码商品：每 100g/ml 能量 × 净含量（能解析出 g/ml 时）；否则按 100g 计。"""
    if energy_kcal_100g is None:
        return None
    grams = 100.0
    if quantity_text:
        import re
        m = re.search(r"(\d+(?:\.\d+)?)\s*(g|ml|克|毫升|G|ML)", quantity_text)
        if m:
            grams = float(m.group(1))
            if grams > 2000:  # 明显是整箱等，回退 100
                grams = 100.0
    return int(round(float(energy_kcal_100g) * grams / 100.0))
